// Collects the license text of every production npm dependency into public/licenses/npm-licenses.txt
// (MIT/ISC/BSD require the notice to travel with the bundled code). Run: node scripts/gen-npm-licenses.mjs
import { execSync } from 'node:child_process'
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'

// packages that ship no license file: the notice from their source header (MIT)
const EXTRA = {
  'qrcode-generator': 'Copyright (c) 2009 Kazuhiko Arase\nLicensed under the MIT license: http://www.opensource.org/licenses/mit-license.php\n(The MIT terms are identical to the license text of the other MIT packages in this file.)\n',
}
const dirs = [...new Set(execSync('npm ls --omit=dev --all --parseable', { encoding: 'utf8' }).split(/\r?\n/).filter(Boolean).slice(1))].sort()
let out = 'License notices of the npm packages bundled in WebGMT (generated by scripts/gen-npm-licenses.mjs)\n'
for (const d of dirs) {
  const pkg = JSON.parse(readFileSync(path.join(d, 'package.json'), 'utf8'))
  const file = readdirSync(d).find((f) => /^(licen[sc]e|copying)(\..*)?$/i.test(f))
  out += `\n${'='.repeat(78)}\n${pkg.name}@${pkg.version} (${typeof pkg.license === 'string' ? pkg.license : JSON.stringify(pkg.license)})\n${'='.repeat(78)}\n`
  out += file && existsSync(path.join(d, file)) ? readFileSync(path.join(d, file), 'utf8') : EXTRA[pkg.name] ?? `(no license file shipped; declared license: ${pkg.license})\n`
}
writeFileSync('public/licenses/npm-licenses.txt', out)
console.log(`${dirs.length} packages -> public/licenses/npm-licenses.txt`)
